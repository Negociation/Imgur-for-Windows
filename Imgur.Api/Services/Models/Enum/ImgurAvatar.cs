        private static readonly Dictionary<string, ImgurAvatar> ByApiValue;
        private static readonly Dictionary<string, ImgurAvatar> BySlug;

        static ImgurAvatarExtensions()
        {
            ByApiValue = new Dictionary<string, ImgurAvatar>(StringComparer.OrdinalIgnoreCase);
            foreach (var pair in ApiValues)
                ByApiValue[pair.Value] = pair.Key;

            BySlug = new Dictionary<string, ImgurAvatar>(StringComparer.OrdinalIgnoreCase);
            foreach (var pair in Slugs)
                BySlug[pair.Value] = pair.Key;
        }

        public static string GetApiValue(this ImgurAvatar avatar)
        {
            string value;
            return ApiValues.TryGetValue(avatar, out value) ? value : null;
        }

        public static string GetSlug(this ImgurAvatar avatar)
        {
            string slug;
            return Slugs.TryGetValue(avatar, out slug) ? slug : null;
        }

        public static string GetLocalImagePath(this ImgurAvatar avatar)
        {
            var slug = avatar.GetSlug();
            return string.IsNullOrEmpty(slug) ? null : "ms-appx:///Assets/Avatars/" + slug + ".png";
        }

        public static bool TryParseApiValue(string apiValue, out ImgurAvatar avatar)
        {
            avatar = default(ImgurAvatar);
            if (string.IsNullOrWhiteSpace(apiValue))
                return false;

            var key = apiValue.Trim();
            if (ByApiValue.TryGetValue(key, out avatar))
                return true;

            // account/me/avatar often returns avatar_name as the bare slug (e.g. "taco").
            if (BySlug.TryGetValue(key, out avatar))
                return true;

            const string flavorPrefix = "flavor/";
            const string defaultPrefix = "default/";
            const string cryptoPrefix = "crypto/";
            if (key.StartsWith(flavorPrefix, StringComparison.OrdinalIgnoreCase))
                return BySlug.TryGetValue(key.Substring(flavorPrefix.Length), out avatar);
            if (key.StartsWith(defaultPrefix, StringComparison.OrdinalIgnoreCase))
                return BySlug.TryGetValue(key.Substring(defaultPrefix.Length), out avatar);
            if (key.StartsWith(cryptoPrefix, StringComparison.OrdinalIgnoreCase))
                return BySlug.TryGetValue(key.Substring(cryptoPrefix.Length), out avatar);

            return false;
        }

        public static bool IsValidApiValue(string apiValue)
        {
            ImgurAvatar ignored;
            return TryParseApiValue(apiValue, out ignored);
        }
